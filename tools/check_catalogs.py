#!/usr/bin/env python3
"""Check that Locale/template.pot and Locale/*.po hold every translatable string.

A string the sources pass to _() but the template lacks can never be translated:
it shows in English in every language.  The template was last regenerated by
hand, so strings added since then went missing without anything failing.  This
extracts the sources as that regeneration did and fails while any string is
missing from the template, or any template string from a catalog.

--update regenerates the template, keeping its header, and merges the catalogs
against it without fuzzy matching, so a new string never borrows the
translation of a different old one; strings that left the sources stay in the
catalogs as obsolete (#~) entries.
"""
import argparse
import datetime
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
KEYWORDS = ["_", "wxTRANSLATE", "wxPLURAL:1,2", "wxGETTEXT_IN_CONTEXT:1c,2",
            "wxGETTEXT_IN_CONTEXT_PLURAL:1c,2,3"]


def tool(name):
    path = shutil.which(name)
    if not path:
        sys.exit("error: %s (gettext) not found" % name)
    return path


def extract(out):
    """Writes the sources' strings to out, in the template's order."""
    sources = sorted(str(p.relative_to(ROOT)) for pattern in ("*.cpp", "*.h")
                     for p in (ROOT / "HikariSub").glob(pattern))
    # The C locale keeps the file order, and so the entry order, the same on
    # every machine.
    env = dict(os.environ, LC_ALL="C")
    subprocess.run([tool("xgettext"), "--language=C++", "--from-code=UTF-8",
                    *("--keyword=" + k for k in KEYWORDS), "--sort-by-file",
                    "--output=" + str(out), *sources],
                   cwd=ROOT, env=env, check=True, stderr=subprocess.DEVNULL)


def missing(defined, used, name):
    """Returns the strings of used that defined lacks, one line each."""
    # In the C locale msgcmp writes the English message the pattern below
    # reads.
    run = subprocess.run([tool("msgcmp"), "--use-untranslated", "--use-fuzzy",
                          str(defined), str(used)],
                         capture_output=True, text=True, encoding="utf-8",
                         env=dict(os.environ, LC_ALL="C"))
    if run.returncode == 0:
        return []
    lines = used.read_text(encoding="utf-8").splitlines()
    found = []
    for line in run.stderr.splitlines():
        hit = re.match(r".*:(\d+): this message is used but not defined", line)
        if not hit:
            continue
        # msgcmp points at the entry's msgstr; its msgid is above it.
        n = int(hit.group(1)) - 1
        while n > 0 and not lines[n].startswith("msgid "):
            n -= 1
        text = re.findall(r'"(.*)"', lines[n])
        n += 1
        while n < len(lines) and lines[n].startswith('"'):
            text += re.findall(r'"(.*)"', lines[n])
            n += 1
        found.append("%s lacks \"%s\"" % (name, "".join(text)))
    return found or [run.stderr.strip()]


def update(locale, extracted):
    template = locale / "template.pot"
    head = template.read_text(encoding="utf-8").split("\n\n", 1)[0]
    stamp = datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M%z")
    head = re.sub(r'"POT-Creation-Date: [^"]*\\n"',
                  lambda _: '"POT-Creation-Date: %s\\n"' % stamp, head)
    body = extracted.read_text(encoding="utf-8").split("\n\n", 1)[1]
    template.write_text(head + "\n\n" + body, encoding="utf-8")
    for po in sorted(locale.glob("*.po")):
        subprocess.run([tool("msgmerge"), "--quiet", "--no-fuzzy-matching",
                        "--no-wrap", "--output-file=" + str(po), str(po),
                        str(template)], check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--update", action="store_true",
                        help="regenerate the template and merge the catalogs")
    args = parser.parse_args()
    locale = ROOT / "Locale"
    with tempfile.TemporaryDirectory() as tmp:
        extracted = pathlib.Path(tmp) / "sources.pot"
        extract(extracted)
        if args.update:
            update(locale, extracted)
        failures = missing(locale / "template.pot", extracted, "Locale/template.pot")
        for po in sorted(locale.glob("*.po")):
            failures += missing(po, locale / "template.pot", "Locale/" + po.name)
    if failures:
        print("\n".join(failures))
        print("Strings are missing from the template or the catalogs; "
              "run tools/check_catalogs.py --update and translate the new ones.")
        return 1
    print("Locale/template.pot and Locale/*.po hold every translatable string.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
