#!/usr/bin/env python3
"""Writes src/core/grammar_rules.inc from Harper's default_config.json and `harper-cli config`."""
import json
import re
import sys

groups = json.load(open(sys.argv[1], encoding="utf-8"))["settings"]
defaults = json.load(open(sys.argv[2], encoding="utf-8"))


def names(settings):
    for s in settings:
        kind, v = next(iter(s.items()))
        if kind == "Bool":
            yield v["name"]
        elif kind == "OneOfMany":
            yield from v["names"]
        else:
            yield from names(v["child"]["settings"])


def slug(label):
    words = re.findall(r"[A-Za-z]+", label)
    return words[0].lower() + "".join(w.capitalize() for w in words[1:])


rows, ids, seen = [], [], set()
for index, g in enumerate(groups):
    g = g["Group"]
    ids.append(slug(g["label"]))
    for name in names(g["child"]["settings"]):
        if name in seen or name not in defaults:
            sys.exit(f"rule {name}: twice, or not in {sys.argv[2]}")
        seen.add(name)
        rows.append((name, index, defaults[name]["default_value"]))
if seen != set(defaults):
    sys.exit(f"ungrouped rules: {sorted(set(defaults) - seen)}")

print("// Generated by tools/harper/rule_table.py from Harper v3.0.0's harper-core/default_config.json")
print("// and `harper-cli config`; do not edit. Each rule: its name, its group, Harper's default.")
print("constexpr std::string_view kGroupIds[] = {")
for i in ids:
    print(f'    "{i}",')
print("};")
print("constexpr Rule kRules[] = {")
for name, index, on in sorted(rows):
    print(f'    {{"{name}", {index}, {"true" if on else "false"}}},')
print("};")
