void appendUtf8(u16 &out, std::span<const std::byte> bytes)
{
    auto at = [&](std::size_t i) { return static_cast<unsigned>(bytes[i]); };
    std::size_t i = 0;
    while (i < bytes.size()) {
        const unsigned b0 = at(i);
        if (b0 < 0x80) {
            out += static_cast<char16_t>(b0);
            ++i;
            continue;
        }
        int need = 0;
        unsigned lo = 0x80, hi = 0xBF;
        char32_t c = 0;
        if (b0 >= 0xC2 && b0 <= 0xDF) {
            need = 1;
            c = b0 & 0x1F;
        } else if (b0 >= 0xE0 && b0 <= 0xEF) {
            need = 2;
            c = b0 & 0x0F;
            lo = b0 == 0xE0 ? 0xA0 : 0x80;
            hi = b0 == 0xED ? 0x9F : 0xBF;
        } else if (b0 >= 0xF0 && b0 <= 0xF4) {
            need = 3;
            c = b0 & 0x07;
            lo = b0 == 0xF0 ? 0x90 : 0x80;
            hi = b0 == 0xF4 ? 0x8F : 0xBF;
        }
        int k = 1;
        for (; k <= need && i + k < bytes.size(); ++k) {
            const unsigned b = at(i + k);
            if (b < (k == 1 ? lo : 0x80) || b > (k == 1 ? hi : 0xBF))
                break;
            c = (c << 6) | (b & 0x3F);
        }
        if (need == 0 || k <= need) {
            out += u'�';
            i += need == 0 ? 1 : k;
            continue;
        }
        if (c < 0x10000) {
            out += static_cast<char16_t>(c);
        } else {
            out += static_cast<char16_t>(0xD800 + ((c - 0x10000) >> 10));
            out += static_cast<char16_t>(0xDC00 + ((c - 0x10000) & 0x3FF));
        }
        i += need + 1;
    }
}

void appendUtf16(u16 &out, std::span<const std::byte> bytes, bool bigEndian)
{
    u16 units;
    for (std::size_t i = 0; i + 1 < bytes.size(); i += 2) {
        const auto first = static_cast<unsigned>(bytes[i]), second = static_cast<unsigned>(bytes[i + 1]);
        units += static_cast<char16_t>(bigEndian ? (first << 8 | second) : (second << 8 | first));
    }
    for (std::size_t i = 0; i < units.size(); ++i) {
        const char16_t c = units[i];
        if (c >= 0xD800 && c <= 0xDBFF && i + 1 < units.size() && units[i + 1] >= 0xDC00 && units[i + 1] <= 0xDFFF) {
            out += c;
            out += units[++i];
        } else {
            out += c >= 0xD800 && c <= 0xDFFF ? u'�' : c;
        }
    }
    if (bytes.size() % 2)
        out += u'�';
}

void appendUtf32(u16 &out, std::span<const std::byte> bytes, bool bigEndian)
{
    for (std::size_t i = 0; i + 3 < bytes.size(); i += 4) {
        char32_t c = 0;
        for (int k = 0; k < 4; ++k)
            c |= static_cast<char32_t>(bytes[i + (bigEndian ? 3 - k : k)]) << (8 * k);
        if (c > 0x10FFFF || (c >= 0xD800 && c <= 0xDFFF))
            out += u'�';
        else if (c < 0x10000)
            out += static_cast<char16_t>(c);
        else {
            out += static_cast<char16_t>(0xD800 + ((c - 0x10000) >> 10));
            out += static_cast<char16_t>(0xDC00 + ((c - 0x10000) & 0x3FF));
        }
    }
    if (bytes.size() % 4)
        out += u'�';
}

// StreamReader(path): a byte order mark picks the encoding, otherwise UTF-8.
u16 decodeText(std::span<const std::byte> bytes)
{
    auto starts = [&](std::initializer_list<unsigned> prefix) {
        if (bytes.size() < prefix.size())
            return false;
        std::size_t i = 0;
        for (unsigned b : prefix)
            if (static_cast<unsigned>(bytes[i++]) != b)
                return false;
        return true;
    };
    u16 out;
    if (starts({0xFE, 0xFF}))
        appendUtf16(out, bytes.subspan(2), true);
    else if (starts({0xFF, 0xFE, 0x00, 0x00}))
        appendUtf32(out, bytes.subspan(4), false);
    else if (starts({0xFF, 0xFE}))
        appendUtf16(out, bytes.subspan(2), false);
    else if (starts({0xEF, 0xBB, 0xBF}))
        appendUtf8(out, bytes.subspan(3));
    else if (starts({0x00, 0x00, 0xFE, 0xFF}))
        appendUtf32(out, bytes.subspan(4), true);
    else
        appendUtf8(out, bytes);
    return out;
}

u16 toCrlf(u16v s)
{
    u16 out;
    for (std::size_t i = 0; i < s.size(); ++i) {
        if (s[i] == u'\r') {
            out += u"\r\n";
            if (i + 1 < s.size() && s[i + 1] == u'\n')
                ++i;
        } else if (s[i] == u'\n') {
            out += u"\r\n";
        } else {
            out += s[i];
        }
    }
    return out;
}

std::optional<int> intAttribute(const xml::Node &elem, u16v name)
{
    const u16 *value = elem.attribute(name);
    if (!value || value->empty())
        return std::nullopt;
    return parseInt(*value);
}

Color fromHtml(u16v html)
{
    if (html.empty())
        return Color();
    if (html.size() != 7 || html.front() != u'#')
        throw ConversionError("One of the identified items was in an invalid format.");
    const auto rgb = parseHex(html.substr(1), false);
    if (!rgb)
        throw ConversionError("One of the identified items was in an invalid format.");
    return Color::fromArgb(0xFF000000u | *rgb);
}

