template<typename T>
void setAtIndex(std::vector<std::optional<T>> &list, int id, T item)
{
    if (id < 0)
        throw ConversionError("Index was out of range. Must be non-negative and less than the size of the collection. (Parameter 'index')");
    if (id >= kMaxHeadId)
        throw ConversionError("Insufficient memory to continue the execution of the program.");
    if (list.size() <= static_cast<std::size_t>(id))
        list.resize(static_cast<std::size_t>(id) + 1);
    list[static_cast<std::size_t>(id)] = std::move(item);
}

template<typename T>
const T *atIndex(const std::vector<std::optional<T>> &list, std::optional<int> id)
{
    if (!id || *id < 0 || static_cast<std::size_t>(*id) >= list.size() || !list[static_cast<std::size_t>(*id)])
        return nullptr;
    return &*list[static_cast<std::size_t>(*id)];
}

Section readPen(const xml::Node &elem)
{
    Section pen;
    pen.font = fontName(intAttribute(elem, u"fs").value_or(0));
    pen.scale = realFontScale(intAttribute(elem, u"sz").value_or(100));
    pen.offset = offsetType(intAttribute(elem, u"of").value_or(1));
    pen.bold = intAttribute(elem, u"b").value_or(0) != 0;
    pen.italic = intAttribute(elem, u"i").value_or(0) != 0;
    pen.underline = intAttribute(elem, u"u").value_or(0) != 0;

    const u16 *fc = elem.attribute(u"fc");
    const int fo = intAttribute(elem, u"fo").value_or(254);
    pen.foreColor = changeAlpha(fromHtml(fc ? u16v(*fc) : u16v(u"#FFFFFF")), fo);

    const u16 *bc = elem.attribute(u"bc");
    pen.backColor = changeAlpha(fromHtml(bc ? u16v(*bc) : u16v(u"#080808")), intAttribute(elem, u"bo").value_or(192));

    if (const int et = intAttribute(elem, u"et").value_or(0); et != 0) {
        const ShadowType type = edgeType(et);
        const u16 *ec = elem.attribute(u"ec");
        pen.shadowColors.add(type, ec ? changeAlpha(fromHtml(*ec), 254) : Color::fromArgb(fo, 0x22, 0x22, 0x22));
    }

    pen.rubyPart = rubyPart(intAttribute(elem, u"rb").value_or(0));
    pen.packed = intAttribute(elem, u"hg").value_or(0) != 0;
    return pen;
}

