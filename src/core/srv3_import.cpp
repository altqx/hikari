std::pair<HorizontalTextDirection, VerticalTextType> textDirections(int printDirection, int scrollDirection)
{
    using H = HorizontalTextDirection;
    switch (printDirection) {
    case 1:
        return {H::RightToLeft, VerticalTextType::None};
    case 2:
        return {scrollDirection == 0 ? H::RightToLeft : H::LeftToRight, VerticalTextType::Positioned};
    case 3:
        return {scrollDirection == 0 ? H::LeftToRight : H::RightToLeft, VerticalTextType::Rotated};
    default:
        return {H::LeftToRight, VerticalTextType::None};
    }
}

