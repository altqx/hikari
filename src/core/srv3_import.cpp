std::expected<std::vector<std::byte>, std::string> assFromSrv3(std::span<const std::byte> ytt)
{
    try {
        const std::vector<srv3::LinePtr> lines = srv3::YttReader().read(srv3::decodeText(ytt));
        const srv3::AssDocument defaults = srv3::readAss(srv3::kDefaultStyles, srv3::builtInStyleOptions());
        const std::u8string bytes = toUtf8(srv3::AssWriter(defaults).save(lines));
        std::vector<std::byte> out(bytes.size());
        std::ranges::transform(bytes, out.begin(), [](char8_t c) { return static_cast<std::byte>(c); });
        return out;
    } catch (const srv3::ConversionError &e) {
        return std::unexpected(std::string(e.what()));
    }
}

bool isSrv3Extension(std::u8string_view extension)
{
    return extension == u8"ytt" || extension == u8"srv3";
}

