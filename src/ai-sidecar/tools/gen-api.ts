import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { kRoot } from "./bundle";

export const kReferenceFile = join(kRoot, "src", "tools", "api.json");
export const kTypesFile = join(kRoot, "src", "tools", "api.gen.ts");

type Schema = Record<string, unknown>;

interface Reference {
    $defs: Record<string, Schema>;
    operations: { name: string; access: "read" | "write"; summary: string; params: Schema; result: Schema }[];
    events: { name: string; summary: string; data: Schema }[];
}

const kIndent = "    ";

function pascal(name: string): string {
    return name.split(/[._]/).map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join("");
}

function doc(text: unknown, indent: string): string {
    return typeof text === "string" ? `${indent}/** ${text.replaceAll("*/", "*\\/")} */\n` : "";
}

function union(alternatives: string[]): string {
    return alternatives.join(" | ");
}

function primitive(type: string): string {
    switch (type) {
    case "integer":
    case "number":
        return "number";
    case "null":
    case "string":
    case "boolean":
        return type;
    case "array":
        return "unknown[]";
    case "object":
        return "Record<string, unknown>";
    default:
        throw new Error(`gen-api: no TypeScript type for JSON Schema type "${type}"`);
    }
}

function objectType(schema: Schema, indent: string): string {
    const properties = (schema.properties ?? {}) as Record<string, Schema>;
    const names = Object.keys(properties);
    if (names.length === 0)
        return schema.additionalProperties === false ? "Record<string, never>" : "Record<string, unknown>";
    const required = new Set((schema.required ?? []) as string[]);
    const inner = indent + kIndent;
    const members = names.map((name) =>
        `${doc(properties[name]!.description, inner)}${inner}${name}${required.has(name) ? "" : "?"}: ${type(properties[name]!, inner)};\n`);
    return `{\n${members.join("")}${indent}}`;
}

/** The TypeScript type of a schema in HA1's JSON Schema subset. */
export function type(schema: Schema, indent = ""): string {
    if (typeof schema.$ref === "string")
        return schema.$ref.replace("#/$defs/", "");
    if ("const" in schema)
        return JSON.stringify(schema.const);
    if (Array.isArray(schema.enum))
        return union(schema.enum.map((value) => JSON.stringify(value)));
    for (const key of ["oneOf", "anyOf"] as const)
        if (Array.isArray(schema[key]))
            return union((schema[key] as Schema[]).map((alternative) => type(alternative, indent)));
    if (Array.isArray(schema.type))
        return union((schema.type as string[]).map(primitive));
    if (schema.type === "array")
        return schema.items ? `${wrapped(type(schema.items as Schema, indent))}[]` : "unknown[]";
    if (schema.type === "object")
        return objectType(schema, indent);
    return typeof schema.type === "string" ? primitive(schema.type) : "unknown";
}

function wrapped(t: string): string {
    return /^[\w"]+$/.test(t) ? t : `(${t})`;
}

/** api.gen.ts for a reference, as `bun tools/gen-api.ts` writes it. */
export function generate(reference: Reference): string {
    let out = "// Generated by `bun tools/gen-api.ts` from api.json, HA1's reference; never edit it by hand.\n\n";
    for (const [name, schema] of Object.entries(reference.$defs))
        out += `${doc(schema.description, "")}export type ${name} = ${type(schema)};\n\n`;
    for (const op of reference.operations) {
        out += `/** ${op.summary} */\nexport type ${pascal(op.name)}Params = ${type(op.params)};\n\n`;
        out += `export type ${pascal(op.name)}Result = ${type(op.result)};\n\n`;
    }
    for (const event of reference.events)
        out += `/** ${event.summary} */\nexport type ${pascal(event.name)}Event = ${type(event.data)};\n\n`;
    out += "export interface Operations {\n";
    for (const op of reference.operations)
        out += `${kIndent}${JSON.stringify(op.name)}: { access: ${JSON.stringify(op.access)}; params: ${pascal(op.name)}Params; ` +
            `result: ${pascal(op.name)}Result };\n`;
    out += "}\n\nexport type OperationName = keyof Operations;\n\nexport interface Events {\n";
    for (const event of reference.events)
        out += `${kIndent}${JSON.stringify(event.name)}: ${pascal(event.name)}Event;\n`;
    return out + "}\n";
}

export function readReference(): Reference {
    return JSON.parse(readFileSync(kReferenceFile, "utf8")) as Reference;
}

if (import.meta.main)
    writeFileSync(kTypesFile, generate(readReference()));
